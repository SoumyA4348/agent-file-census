"""Paper tables from a scanned corpus DB (data/scan.sqlite): coverage funnel, hidden-channel prevalence by platform
vs the README/CONTRIBUTING control, detector verdicts. Unit = unique blob (symlinks excluded). Wilson 95% CIs.

    python -I src/tables.py --ver 0.3.1 [--db data/scan.sqlite] [--out notes/results_0.3.1.md]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from corpus import DB  # noqa: E402
from test_sample import wilson  # noqa: E402

# channel -> test on the features dict
CHANNELS = {
    "any hidden channel": lambda f: bool(f["hidden"]) or f["tag_chars"] > 0 or f["bidi"] > 0,
    "hidden instruction": lambda f: f["hidden_instr"] > 0,
    "HTML comment": lambda f: f["html_comments"] > 0,
    "Unicode tag chars": lambda f: f["tag_chars"] > 0,
    "zero-width run": lambda f: f["zw_runs"] > 0,
    "bidi control": lambda f: f["bidi"] > 0,
    "hidden HTML": lambda f: "hidden_html" in f["hidden"],
    "markdown comment": lambda f: "md_comment" in f["hidden"],
    "empty link / long alt": lambda f: "empty_link" in f["hidden"] or "image_alt" in f["hidden"],
    "base64 text": lambda f: "base64_text" in f["hidden"],
    "exfil-type URL": lambda f: f["exfil_urls"] > 0,
    "pipe to shell": lambda f: f["pipe_shell"] > 0,
}


def pct(k, n):
    lo, hi = wilson(k, n)
    return f"{k / n:.2%} ({lo:.2%}–{hi:.2%})" if n else "–"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--ver", required=True)
    p.add_argument("--db", default=str(DB))
    p.add_argument("--out")
    p.add_argument("--min-n", type=int, default=200, help="platforms with fewer scanned blobs go to 'other'")
    a = p.parse_args()
    con = sqlite3.connect(f"file:{pathlib.Path(a.db).resolve().as_posix()}?mode=ro", uri=True)
    L = [f"# Results, afscan {a.ver} (unique blobs; generated by src/tables.py)", ""]

    # 1. coverage funnel
    L += ["## Coverage", "", "| kind | targets | mapped | kept (hash-verified) | missing on S3 | not visible | too big | "
          "errors | scanned |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    q = """SELECT t.kind, COUNT(*), COUNT(b.sha1_git), SUM(f.state='ok'), SUM(f.state='missing'),
           SUM(f.state='not_visible'), SUM(f.state='too_big'), SUM(f.state IN ('error','hash_mismatch')),
           COUNT(x.sha1_git) FROM targets t LEFT JOIN blobs b ON b.sha1_git=t.target
           LEFT JOIN fetch f ON f.sha1_git=t.target LEFT JOIN findings x ON x.sha1_git=t.target AND x.ver=?
           GROUP BY 1 ORDER BY 2 DESC"""
    for kind, *v in con.execute(q, (a.ver,)):
        L.append(f"| {kind} | " + " | ".join(f"{x or 0:,}" for x in v) + " |")

    # 2. channel prevalence by platform (agent files) vs control
    rows = con.execute("SELECT t.kind, t.tool, ft.data FROM features ft JOIN targets t ON t.target=ft.sha1_git "
                       "WHERE ft.ver=? AND t.link=0 AND ft.data IS NOT NULL", (a.ver,)).fetchall()
    groups: dict[str, list] = {}
    for kind, tool, data in rows:
        if kind in ("agent", "hop1", "hop2"):
            key = tool if kind == "agent" else f"{tool} ({kind})"
        elif kind == "base" and tool in ("readme.md", "contributing.md"):
            key = "CONTROL README/CONTRIBUTING"
        else:
            continue
        groups.setdefault(key, []).append(json.loads(data))
    small = [k for k, v in groups.items() if len(v) < a.min_n and not k.startswith("CONTROL")]
    if small:
        groups.setdefault("other agent files", []).extend(f for k in small for f in groups.pop(k))
    agent_all = [f for k, v in groups.items() if not k.startswith("CONTROL") for f in v]
    order = sorted((k for k in groups if not k.startswith("CONTROL")), key=lambda k: -len(groups[k]))
    cols = ["any hidden channel", "hidden instruction", "HTML comment", "Unicode tag chars", "zero-width run",
            "bidi control", "hidden HTML", "base64 text"]
    L += ["", "## Hidden channels by platform (share of unique blobs with >= 1)", "",
          "| platform | blobs | " + " | ".join(cols) + " |", "|---|---:|" + "---:|" * len(cols)]
    for key, fs in [(k, groups[k]) for k in order] + [("ALL agent files", agent_all)] + \
            [(k, v) for k, v in groups.items() if k.startswith("CONTROL")]:
        L.append(f"| {key} | {len(fs):,} | " + " | ".join(pct(sum(CHANNELS[c](f) for f in fs), len(fs)) for c in cols)
                 + " |")
    L += ["", "## All channels, all agent files vs control", "", "| channel | agent files | control |", "|---|---:|---:|"]
    ctl = groups.get("CONTROL README/CONTRIBUTING", [])
    for c, fn in CHANNELS.items():
        L.append(f"| {c} | {pct(sum(fn(f) for f in agent_all), len(agent_all))} | {pct(sum(fn(f) for f in ctl), len(ctl))} |")

    # 3. verdicts
    L += ["", "## Detector verdicts (agent files)", "", "| platform | scanned | high | medium | low | info | clean |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    q = ("SELECT t.tool, COUNT(*), SUM(verdict='high'), SUM(verdict='medium'), SUM(verdict='low'), SUM(verdict='info'), "
         "SUM(verdict='clean') FROM findings x JOIN targets t ON t.target=x.sha1_git WHERE x.ver=? AND t.link=0 "
         "AND t.kind IN ('agent','hop1','hop2') GROUP BY 1 ORDER BY 2 DESC")
    for tool, n, *v in con.execute(q, (a.ver,)):
        L.append(f"| {tool} | {n:,} | " + " | ".join(f"{x:,}" for x in v) + " |")
    out = pathlib.Path(a.out or ROOT / "notes" / f"results_{a.ver}.md")
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"-> {out} ({len(rows):,} feature rows)")


if __name__ == "__main__":
    main()
